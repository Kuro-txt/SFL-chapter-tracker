export function calculateTrackTickets(points, isVip = false) {
  const p = Number(points) || 0;
  if (p <= 0) return 0;

  let totalTickets = 0;
  for (const m of ASCENSION_AGE_CHAPTER_TRACKS.milestones) {
    if (m.points > p) break;

    // Free tier tickets
    if (m.free?.items?.["Shiny Feather"]) {
      totalTickets += Number(m.free.items["Shiny Feather"]) || 0;
    }

    // Premium tier tickets (only if VIP is active)
    if (isVip && m.premium?.items?.["Shiny Feather"]) {
      totalTickets += Number(m.premium.items["Shiny Feather"]) || 0;
    }
  }

  return totalTickets;
}
